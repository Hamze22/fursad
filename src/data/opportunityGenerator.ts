    const degree = degreeLevels[(counter * 3) % degreeLevels.length];
    
    const year = counter % 3 === 0 ? '2026' : '2027';
    const month = months[(counter * 5) % 12];
    const day = (10 + (counter % 18)).toString().padStart(2, '0');
    const openingMonth = ((counter * 7) % 12) + 1;
    const openingDay = (1 + (counter % 28)).toString().padStart(2, '0');
